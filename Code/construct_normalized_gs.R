## Full matrix
## The rows and columns of this are named with the gene and spot barcodes, so when
## you have all of them (for all the genes and sections), can reorder to match the raw, 
## sctransform, and NormalizeData gene spot matrices.
spcounts_unordered <- do.call(rbind, lapply(all_normalized_matrices, "[[", "normalized_gs_matrix"))

## Since this is an example with just a subset of the full g-s matrix, I will just
## output this as is without reordering the rows and columns.
spcounts <- spcounts_unordered


plot_gene_count <- function(gene_name, dot_size=2) {
  gene_name_short <- (features %>% filter(gene_long==gene_name))$gene
  gene_spcounts <- spcounts[which(rownames(spcounts)==gene_name),]
  gene_spdata <- data.frame(
    spot_name=names(gene_spcounts),
    spcount=unname(gene_spcounts)
  )
  coord_data <- real_coords %>% data.frame()
  coord_data$spot_name <- rownames(coord_data)
  
  plot_data <- coord_data %>%
    left_join(gene_spdata, by="spot_name") %>%
    filter(!is.na(spcount))
  count_plot <- ggplot(plot_data, aes(x=x,y=y,color=spcount)) +
    geom_point(size=dot_size) +
    scale_color_viridis_c(option="magma") + 
    theme_classic() +
    theme(axis.text.x=element_blank(), axis.text.y=element_blank(),
          axis.ticks.x=element_blank(), axis.ticks.y=element_blank()) +
    labs(color="Count",
         title=paste0("Spatially Normalized Counts for ", gene_name, " (", gene_name_short, ")"),
         x="",y="")
  return(count_plot)
}

plot_gene_count(rownames(spcounts)[2], dot_size=16)

write_rds(spcounts, file=here("Processed Data", "spcounts.rds"))


